export function createEmptyLedgerState(primaryCurrency: CurrencyCode = 'USD'): FinoraLedgerState {
  const now = new Date().toISOString();
  return {
    version: 1,
    isSampleData: false,
    lastUpdated: now,
    preferences: {
      primaryCurrency,
      locale: 'en-US',
      dateFormat: 'MMM D, YYYY',
      defaultDatePreset: 'this-month',
      dashboardWidgetOrder: [...DEFAULT_DASHBOARD_WIDGET_ORDER],
      hiddenDashboardWidgets: [],
      defaultBudgetAlertThresholdPct: 80,
    },
    fxRates: [],
    accounts: [
      {
        id: 'acc-primary',
        name: 'Primary Checking',
        type: 'checking',
        currency: primaryCurrency,
        openingBalanceMinor: 0,
        description: 'Default day-to-day transaction account',
        includeInTotal: true,
        archived: false,
        createdAt: now,
      },
    ],
    categories: DEFAULT_CATEGORIES.map((c) => ({ ...c })),
    transactions: [],
    budgets: [],
    savingsGoals: [],
    goalTransactions: [],
    bills: [],
    subscriptions: [],
    recurringRules: [],
    activityLog: [
      {
        id: 'act-init',
        timestamp: now,
        action: 'Workspace Initialized',
        entityType: 'system',
        entityId: 'workspace',
        summary: `Started fresh Finora ledger in ${primaryCurrency}.`,
      },
    ],
  };
}

